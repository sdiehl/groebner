//! C ABI over strings: polynomials go in and come out in the [`PolynomialRing`] syntax.
//!
//! Each entry point takes a comma separated variable list, an order (`lex`, `grlex` or
//! `grevlex`), a modulus (0 for the rationals, otherwise a prime) and `;` separated
//! polynomials. It returns 0 and writes a newline separated result to `out`, or a nonzero
//! code and an error message. Strings written to `out` are freed with [`gb_string_free`].
#![allow(unsafe_code)]

use std::ffi::{CStr, CString, c_char, c_int};
use std::panic::{AssertUnwindSafe, catch_unwind};

use num_rational::BigRational;

use crate::{
    F4Field, GroebnerError, Ideal, MonomialOrder, ParseCoefficient, ParsePolynomialError,
    PolynomialRing, Zp, groebner_basis_f4,
};

/// Status codes returned by every entry point.
#[repr(C)]
pub enum GbResult {
    Success = 0,
    InvalidArgument = 1,
    ParseError = 2,
    ComputeError = 3,
    Panic = 4,
}

struct Request<'a> {
    vars: Vec<&'a str>,
    order: MonomialOrder,
    modulus: u64,
    polys: &'a str,
}

struct Failure(GbResult, String);

impl From<ParsePolynomialError> for Failure {
    fn from(e: ParsePolynomialError) -> Self {
        Self(GbResult::ParseError, e.to_string())
    }
}

impl From<GroebnerError> for Failure {
    fn from(e: GroebnerError) -> Self {
        Self(GbResult::ComputeError, e.to_string())
    }
}

fn invalid(e: impl Into<String>) -> Failure {
    Failure(GbResult::InvalidArgument, e.into())
}

fn ring<F>(r: &Request<'_>) -> Result<PolynomialRing<F>, Failure> {
    let ring = if r.modulus == 0 {
        PolynomialRing::new(r.vars.iter().copied(), r.order.clone())
    } else {
        PolynomialRing::with_modulus(r.vars.iter().copied(), r.order.clone(), r.modulus)
    };
    ring.map_err(|e| invalid(e.to_string()))
}

fn basis<F: F4Field + ParseCoefficient>(r: &Request<'_>) -> Result<String, Failure> {
    let ring = ring::<F>(r)?;
    let polys = ring.parse_many(r.polys)?;
    let basis = groebner_basis_f4(polys, true)?;
    let lines: Result<Vec<_>, _> = basis.iter().map(|p| ring.format(p)).collect();
    Ok(lines?.join("\n"))
}

fn reduce<F: F4Field + ParseCoefficient>(r: &Request<'_>, f: &str) -> Result<String, Failure> {
    let ring = ring::<F>(r)?;
    let ideal = Ideal::new(ring.parse_many(r.polys)?)?;
    let f = ring.parse(f)?;
    Ok(ring.format(&ideal.normal_form(&f))?)
}

unsafe fn str_arg<'a>(s: *const c_char) -> Result<&'a str, Failure> {
    if s.is_null() {
        return Err(invalid("null string"));
    }
    unsafe { CStr::from_ptr(s) }
        .to_str()
        .map_err(|e| invalid(e.to_string()))
}

unsafe fn request<'a>(
    vars: *const c_char,
    order: *const c_char,
    modulus: u64,
    polys: *const c_char,
) -> Result<Request<'a>, Failure> {
    let vars = unsafe { str_arg(vars)? }
        .split(',')
        .map(str::trim)
        .collect();
    let order = unsafe { str_arg(order)? }.parse().map_err(invalid)?;
    let polys = unsafe { str_arg(polys)? };
    Ok(Request {
        vars,
        order,
        modulus,
        polys,
    })
}

unsafe fn respond(out: *mut *mut c_char, run: impl FnOnce() -> Result<String, Failure>) -> c_int {
    let (code, text) = match catch_unwind(AssertUnwindSafe(run)) {
        Ok(Ok(text)) => (GbResult::Success, text),
        Ok(Err(Failure(code, text))) => (code, text),
        Err(_) => (GbResult::Panic, "internal panic".into()),
    };
    if !out.is_null() {
        let text = CString::new(text).unwrap_or_default();
        unsafe { *out = text.into_raw() };
    }
    code as c_int
}

/// Reduced Groebner basis of `polys`, one polynomial per line.
///
/// # Safety
/// String arguments must be valid null terminated UTF-8. `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gb_groebner_basis(
    vars: *const c_char,
    order: *const c_char,
    modulus: u64,
    polys: *const c_char,
    out: *mut *mut c_char,
) -> c_int {
    unsafe {
        respond(out, || {
            let r = request(vars, order, modulus, polys)?;
            if modulus == 0 {
                basis::<BigRational>(&r)
            } else {
                basis::<Zp>(&r)
            }
        })
    }
}

/// Normal form of `f` modulo the ideal generated by `polys`.
///
/// # Safety
/// String arguments must be valid null terminated UTF-8. `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gb_reduce(
    vars: *const c_char,
    order: *const c_char,
    modulus: u64,
    polys: *const c_char,
    f: *const c_char,
    out: *mut *mut c_char,
) -> c_int {
    unsafe {
        respond(out, || {
            let r = request(vars, order, modulus, polys)?;
            let f = str_arg(f)?;
            if modulus == 0 {
                reduce::<BigRational>(&r, f)
            } else {
                reduce::<Zp>(&r, f)
            }
        })
    }
}

/// Free a string written by this library.
///
/// # Safety
/// `s` must be null or a pointer previously written to `out` by this library.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gb_string_free(s: *mut c_char) {
    if !s.is_null() {
        drop(unsafe { CString::from_raw(s) });
    }
}
